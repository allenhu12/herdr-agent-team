#!/usr/bin/env python3
"""Render the read-only Role Tree from one team.yaml.

Usage: render-role-tree.py <team.yaml> > <team_dir>/role-tree.md

team.yaml is the only input. team-state.yaml is never read, so the same
team.yaml always renders the same tree. Exit 2 when team.yaml breaks the
fixed pane chain or uses an effort level the role's kind does not accept.
"""
import sys
from os.path import normpath
from pathlib import Path

import yaml

# Effort levels per kind, from installed CLI help (see identity-and-launch.md).
EFFORT_BY_KIND = {
    "claude": {"low", "medium", "high", "xhigh", "max"},
    "codex": {"low", "medium", "high", "xhigh"},
}


def chain_errors(team):
    """Fixed chain: role 1 right from lead, role N down from role N-1."""
    errors = []
    roles = team.get("roles") or []
    names = [r.get("name") for r in roles]
    if len(set(names)) != len(names):
        errors.append("role names are not unique")
    for i, role in enumerate(roles):
        pos = role.get("position") or {}
        want = ("right", "lead") if i == 0 else ("down", names[i - 1])
        got = (pos.get("direction"), pos.get("from"))
        if got != want:
            errors.append(f"{role.get('name')}: position {got[0]} from {got[1]}, "
                          f"fixed chain needs {want[0]} from {want[1]}")
    return errors


def effort_errors(team):
    errors = []
    specs = [(r.get("name"), r.get("kind"), r.get("effort")) for r in team.get("roles") or []]
    lead = team.get("lead") or {}
    if lead.get("mode") == "spawned":
        specs.append((lead.get("name"), lead.get("kind"), lead.get("effort")))
    if lead.get("suggested"):
        s = lead["suggested"]
        specs.append(("lead.suggested", s.get("kind"), s.get("effort")))
    for name, kind, effort in specs:
        allowed = EFFORT_BY_KIND.get(kind)
        if allowed is not None and effort not in allowed:
            errors.append(f"{name}: effort '{effort}' is not valid for kind '{kind}' "
                          f"(allowed: {', '.join(sorted(allowed))})")
    return errors


def context_root_errors(team):
    errors = []
    for role in team.get("roles") or []:
        roots = role.get("context_roots", [])
        name = role.get("name")
        if not isinstance(roots, list):
            errors.append(f"{name}: context_roots must be a list of absolute directories")
            continue
        seen = set()
        for root in roots:
            if not isinstance(root, str) or not root.strip() or not Path(root).is_absolute():
                errors.append(f"{name}: context_roots entries must be non-empty absolute paths")
                continue
            normalized = normpath(root)
            if normalized in seen:
                errors.append(f"{name}: context_roots contains a duplicate root")
            seen.add(normalized)
    return errors


def validate(team):
    return chain_errors(team) + effort_errors(team) + context_root_errors(team)


def _v(value):
    return "unknown" if value in (None, "") else str(value)


def lead_line(team):
    lead = team.get("lead") or {}
    if team.get("template"):
        s = lead.get("suggested") or {}
        return ("lead  [template suggestion]",
                f"{_v(s.get('kind'))} · {_v(s.get('model'))} · {_v(s.get('effort'))}",
                s.get("responsibility") or "")
    mode = {"session": "this session", "spawned": "spawned"}.get(lead.get("mode"), "mode unknown")
    resp = (lead.get("suggested") or {}).get("responsibility") or ""
    return (f"{_v(lead.get('name'))}  [{mode}]",
            f"{_v(lead.get('kind'))} · {_v(lead.get('model'))} · {_v(lead.get('effort'))}",
            resp)


def render(team):
    roles = team.get("roles") or []
    head, spec, resp = lead_line(team)
    title = team.get("team_id") or ("template" if team.get("template") else "default")
    out = [f"# Role Tree: {title} ({_v(team.get('team_type'))})", "",
           "Rendered from team.yaml. Do not edit this file; change team.yaml",
           "and re-render.", "", "```text", head, f"|  {spec}"]
    if resp:
        out.append(f"|  {resp}")
    for i, r in enumerate(roles):
        last = i == len(roles) - 1
        branch, cont = ("`-- ", "    ") if last else ("+-- ", "|   ")
        mark = "  [prompt]" if r.get("prompt_file") else ""
        mark += "  [context]" if r.get("context_roots") else ""
        out.append("|")
        out.append(f"{branch}{_v(r.get('name'))}{mark}")
        out.append(f"{cont}  {_v(r.get('kind'))} · {_v(r.get('model'))} · "
                   f"{_v(r.get('effort'))} · {_v(r.get('access'))}")
        if r.get("responsibility"):
            out.append(f"{cont}  {r['responsibility']}")
    out += ["```", "", "## Pane layout", "", "```text"]
    lead_name = head.split("  [")[0]
    names = [_v(r.get("name")) for r in roles] or ["(no Sub-Agents)"]
    lw = max(len(lead_name), 8) + 2
    rw = max(len(n) for n in names) + 2
    sep = "+" + "-" * lw + "+" + "-" * rw + "+"
    out.append(sep)
    mid = len(names) // 2
    for i, n in enumerate(names):
        left = lead_name if i == mid else ""
        out.append("|" + left.center(lw) + "|" + n.center(rw) + "|")
        if i < len(names) - 1:
            out.append("|" + " " * lw + "+" + "-" * rw + "+")
    out += [sep, "```", ""]
    return "\n".join(out)


def main(argv):
    if len(argv) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 1
    team = yaml.safe_load(Path(argv[1]).read_text(encoding="utf-8"))
    errors = validate(team)
    if errors:
        print("role tree not rendered; team.yaml is invalid:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 2
    sys.stdout.write(render(team))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
